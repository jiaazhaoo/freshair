def mtime(path: Path) -> float:
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0


# --------------------------------------------------------------------------
# Codex sessions
#
# Codex files a "rollout" per session under
# $CODEX_HOME/sessions/YYYY/MM/DD/rollout-<timestamp>-<uuid>.jsonl, with the
# first line a session_meta carrying the directory the session ran in. Records
# come in two generations: newer Codex writes conversation turns as
# `response_item` entries, older ones as `event_msg`. Both are read, and the
# newer stream wins when a file has both, so turns are not counted twice.
# --------------------------------------------------------------------------

def codex_home() -> Path:
    return Path(os.environ.get("CODEX_HOME") or (Path.home() / ".codex"))


def codex_session_cwd(path: Path) -> str:
    """The directory a rollout was recorded in, from its session_meta header."""
    try:
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            for _ in range(5):
                line = fh.readline()
                if not line:
                    break
                try:
                    rec = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if rec.get("type") != "session_meta":
                    continue
                payload = rec.get("payload") or rec
                return str(payload.get("cwd") or "")
    except OSError:
        pass
    return ""


def codex_transcripts(cwd: Path) -> list[Path]:
    home = codex_home()
    files: list[Path] = []
    for root in (home / "sessions", home / "archived_sessions"):
        if root.is_dir():
            files.extend(root.rglob("rollout-*.jsonl"))
    files.sort(key=mtime, reverse=True)

    # Only sessions belonging to this project. A session started at the repo
    # root is still ours when we are invoked from a subdirectory.
    def norm(path: str) -> str:
        # Codex records whatever string it was started with; symlinked homes,
        # bind mounts and trailing slashes must not silently drop a session.
        try:
            return str(Path(path).expanduser().resolve())
        except (OSError, RuntimeError):
            return path.rstrip(os.sep)

    here = norm(str(cwd))
    owned = []
    for f in files:
        raw = codex_session_cwd(f)
        if not raw:
            continue
        session_cwd = norm(raw)
        if here == session_cwd or here.startswith(session_cwd + os.sep):
            owned.append(f)
    # (2) never hand back a review we ourselves spawned
    return [f for f in owned if not is_freshair_child(f)]


def codex_blocks_text(content) -> str:
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    parts = []
    for block in content:
        if isinstance(block, str):
            parts.append(block)
        elif isinstance(block, dict):
            # input_text on user turns, output_text on assistant turns, and
            # plain text on anything written before that split existed.
            parts.append(block.get("text") or block.get("content") or "")
    return "\n".join(p for p in parts if p).strip()


def parse_codex(path: Path, keep_thinking: bool) -> list[dict]:
    items: list[dict] = []   # from response_item — the current format
    events: list[dict] = []  # from event_msg — the legacy one
    saw_item_message = False  # a tool call is not evidence of a conversation

    with path.open("r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue

            kind = rec.get("type")
            payload = rec.get("payload") or {}
            if not isinstance(payload, dict):
                continue
            ptype = payload.get("type")
            ts = rec.get("timestamp", "")

            if kind == "response_item":
                if ptype == "message":
                    role = payload.get("role")
                    if role == "developer":
                        continue  # harness scaffolding, not the conversation
                    text = codex_blocks_text(payload.get("content"))
                    role = "user" if role == "user" else "assistant"
                    if text.strip():
                        saw_item_message = True
                elif ptype == "function_call":
                    args = payload.get("arguments")
                    text = (f"[tool: {payload.get('name', 'tool')}] "
                            f"{clip(str(args), 400)}")
                    role = "assistant"
                elif ptype == "function_call_output":
                    out = payload.get("output")
                    if isinstance(out, dict):
                        out = out.get("content", out)
                    text = f"[tool result]\n{clip(str(out), TOOL_RESULT_CAP)}"
                    role = "tool"
                elif ptype == "reasoning":
                    if not keep_thinking:
                        continue
                    text = "[thinking] " + codex_blocks_text(
                        payload.get("summary") or payload.get("content"))
                    role = "assistant"
                else:
                    continue
                if text.strip():
                    items.append({"role": role, "text": text.strip(), "ts": ts})

            elif kind == "event_msg":
                if ptype == "user_message":
                    role = "user"
                elif ptype == "agent_message":
                    role = "assistant"
                else:
                    continue
                text = payload.get("message") or payload.get("text") or ""
                if text.strip():
                    events.append({"role": role, "text": text.strip(), "ts": ts})

    # A response_item stream carrying only tool records is not a conversation;
    # the legacy event stream may still hold the real one.
    turns = items if saw_item_message else events
    return [t for t in turns if not is_own_payload(t["text"])]


def project_dir_for(cwd: Path) -> Path:
    """Claude Code slugifies the cwd: every non-alphanumeric char becomes '-'."""
    slug = re.sub(r"[^a-zA-Z0-9]", "-", str(cwd))
    return Path.home() / ".claude" / "projects" / slug


def claude_transcripts(cwd: Path) -> list[Path]:
    pdir = project_dir_for(cwd)
    if not pdir.is_dir():
        return []
    files = sorted(pdir.glob("*.jsonl"), key=mtime, reverse=True)
    return [f for f in files if not is_freshair_child(f)]


SESSION_SOURCES = {
    "claude": {"find": claude_transcripts, "label": "Claude Code"},
    "codex": {"find": codex_transcripts, "label": "Codex"},
}


def find_transcript(explicit: str | None, cwd: Path, session_id: str | None = None,
                    source: str = "auto") -> tuple[Path, str]:
    """Locate the session to review, and say which host wrote it."""
    if explicit:
        path = Path(explicit).expanduser()
        if not path.is_file():
            die(f"transcript not found: {path}")
        if source == "auto":
            source = "codex" if path.name.startswith("rollout-") else "claude"
        return path, source

    # An exact session id beats any heuristic.
    session_id = (
        session_id
        or os.environ.get("CLAUDE_SESSION_ID")
        or os.environ.get("CLAUDE_CODE_SESSION_ID")
    )
    if session_id and source in ("auto", "claude"):
        candidate = project_dir_for(cwd) / f"{session_id}.jsonl"
        if candidate.is_file():
            return candidate, "claude"

    wanted = list(SESSION_SOURCES) if source == "auto" else [source]
    if source != "auto" and source not in SESSION_SOURCES:
        die(f"unknown session source {source!r}. Known: "
            + ", ".join(list(SESSION_SOURCES) + ["auto"]))

    # Newest wins: the session being appended to right now is the live one.
    best: tuple[float, Path, str] | None = None
    for name in wanted:
        found = SESSION_SOURCES[name]["find"](cwd)
        if found and (best is None or mtime(found[0]) > best[0]):
            best = (mtime(found[0]), found[0], name)

    if best is None:
        looked = ", ".join(
            f"{SESSION_SOURCES[n]['label']} ({project_dir_for(cwd) if n == 'claude' else codex_home() / 'sessions'})"
            for n in wanted
        )
        die(f"no session found for {cwd}.\nLooked in: {looked}\n"
            "Pass --transcript /path/to/session.jsonl to name one explicitly.")

    return best[1], best[2]


def is_freshair_child(path: Path) -> bool:
    """True if this transcript is a review we ourselves spawned.

    A CLI backend run in the project directory leaves its own session log next
    to the real one, and it is always the newest. Without this check the
    fallback would review the reviewer.
    """
    try:
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            for _ in range(40):
                line = fh.readline()
                if not line:
                    break
                if is_own_payload(line):
                    return True
    except OSError:
        pass
    return False


