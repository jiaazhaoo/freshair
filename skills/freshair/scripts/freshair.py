def project_dir_for(cwd: Path) -> Path:
    """Claude Code slugifies the cwd: every non-alphanumeric char becomes '-'."""
    slug = re.sub(r"[^a-zA-Z0-9]", "-", str(cwd))
    return Path.home() / ".claude" / "projects" / slug


def find_transcript(explicit: str | None, cwd: Path, session_id: str | None = None) -> Path:
    if explicit:
        p = Path(explicit).expanduser()
        if not p.is_file():
            die(f"transcript not found: {p}")
        return p

    pdir = project_dir_for(cwd)
    if not pdir.is_dir():
        die(
            f"no session directory for {cwd} (looked in {pdir}).\n"
            "Pass --transcript /path/to/session.jsonl explicitly."
        )

    session_id = (
        session_id
        or os.environ.get("CLAUDE_SESSION_ID")
        or os.environ.get("CLAUDE_CODE_SESSION_ID")
    )
    if session_id:
        candidate = pdir / f"{session_id}.jsonl"
        if candidate.is_file():
            return candidate

    # Fall back to the most recently written transcript in this project — in a
    # live session that is the one being appended to right now.
    files = sorted(pdir.glob("*.jsonl"), key=lambda f: f.stat().st_mtime, reverse=True)
    if not files:
        die(f"no .jsonl transcripts in {pdir}")
    for candidate in files:
        if not is_freshair_child(candidate):
            return candidate
    return files[0]


def is_freshair_child(path: Path) -> bool:
    """True if this transcript is a review we ourselves spawned.

    A CLI backend run in the project directory leaves its own session log next
    to the real one, and it is always the newest. Without this check the
    fallback would review the reviewer.
    """
    try:
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            for _ in range(40):
                line = fh.readline()
                if not line:
                    break
                if FRESHAIR_MARKER in line or any(sig in line for sig in LEGACY_SIGNATURES):
                    return True
    except OSError:
        pass
    return False


