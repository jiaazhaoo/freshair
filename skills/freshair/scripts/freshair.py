def config_files(cwd: Path) -> list[tuple[Path, dict]]:
    """User-global first, then per-repo — later files win on conflict."""
    found = []
    for path in (USER_CONFIG,
                 Path.home() / ".config" / "wdyt" / "config.json",   # pre-rename
                 cwd / ".freshair.json",
                 cwd / ".wdyt.json"):                                # pre-rename
        if not path.is_file():
            continue
        try:
            found.append((path, json.loads(path.read_text(encoding="utf-8"))))
        except json.JSONDecodeError:
            print(f"freshair: ignoring malformed config at {path}", file=sys.stderr)
    return found


def load_config(cwd: Path) -> dict:
    merged: dict = {}
    for path, data in config_files(cwd):
        if "api_key" in data and path not in (USER_CONFIG,
                                              Path.home() / ".config" / "wdyt" / "config.json"):
            # A repo config gets committed. A key belongs in the user-global
            # one, which does not.
            print(f"freshair: ignoring api_key in {path} — it would be committed. "
                  f"Use --set-key, which writes to {USER_CONFIG}.", file=sys.stderr)
            data = {k: v for k, v in data.items() if k != "api_key"}
        merged.update(data)
    return merged


def openrouter_key(config: dict) -> str:
    """Environment first, so a shell export still overrides a stored key."""
    return (os.environ.get("OPENROUTER_API_KEY", "").strip()
            or str(config.get("api_key", "")).strip())


def write_user_config(update: dict) -> Path:
    USER_CONFIG.parent.mkdir(parents=True, exist_ok=True)
    current = {}
    if USER_CONFIG.is_file():
        try:
            current = json.loads(USER_CONFIG.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            pass
    current.update({k: v for k, v in update.items() if v is not None})
    USER_CONFIG.write_text(json.dumps(current, indent=2) + "\n", encoding="utf-8")
    try:
        USER_CONFIG.chmod(0o600)   # it can hold a key
    except OSError:
        pass
    return USER_CONFIG


# --------------------------------------------------------------------------
# Signing in to OpenRouter without handling the key
#
# OAuth PKCE: we hold a random secret, send only its hash to OpenRouter, and
# the user approves in a browser. The key comes back over a loopback callback
# and goes straight to disk — it is never shown, pasted, or put in a shell
# history. https://openrouter.ai/docs/guides/overview/auth/oauth
# --------------------------------------------------------------------------

OPENROUTER_AUTH_URL = "https://openrouter.ai/auth"
OPENROUTER_KEYS_URL = "https://openrouter.ai/api/v1/auth/keys"

CALLBACK_PAGE = b"""<!doctype html><meta charset="utf-8">
<title>FreshAir</title>
<style>body{font:16px system-ui;margin:4rem auto;max-width:28rem;color:#222}
code{background:#f4f4f5;padding:.15em .4em;border-radius:4px}</style>
<h2>Connected.</h2>
<p>Your OpenRouter key was saved to this machine. You can close this tab and go
back to the terminal.</p>
<p>Ask for an outside opinion with <code>/freshair</code>.</p>
"""


def pkce_pair() -> tuple[str, str]:
    """A verifier we keep, and the S256 challenge we hand out (RFC 7636)."""
    verifier = base64.urlsafe_b64encode(secrets.token_bytes(48)).decode().rstrip("=")
    digest = hashlib.sha256(verifier.encode("ascii")).digest()
    challenge = base64.urlsafe_b64encode(digest).decode().rstrip("=")
    return verifier, challenge


def await_oauth_code(timeout: int) -> tuple[str, "object"]:
    """Bind a loopback callback and return (auth_url_callback, server)."""
    received: dict[str, str] = {}

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):  # noqa: N802 — http.server's interface
            query = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
            received["code"] = (query.get("code") or [""])[0]
            received["error"] = (query.get("error") or [""])[0]
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.end_headers()
            self.wfile.write(CALLBACK_PAGE)

        def log_message(self, *a):  # keep the terminal clean
            pass

    server = http.server.HTTPServer(("127.0.0.1", 0), Handler)
    server.timeout = timeout
    return f"http://localhost:{server.server_port}/callback", (server, received)


def exchange_code(code: str, verifier: str, timeout: int) -> str:
    payload = json.dumps({
        "code": code,
        "code_verifier": verifier,
        "code_challenge_method": "S256",
    }).encode()
    req = urllib.request.Request(
        OPENROUTER_KEYS_URL, data=payload,
        headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = json.loads(resp.read().decode())
    except urllib.error.HTTPError as e:
        detail = e.read().decode("utf-8", "replace")[:300]
        hint = ""
        if e.code == 403:
            hint = ("\n  A 403 here usually means the browser session was not "
                    "signed in to OpenRouter. Sign in there first, then retry.")
        die(f"OpenRouter refused the exchange (HTTP {e.code}): {detail}{hint}")
    except Exception as e:  # noqa: BLE001
        die(f"could not reach OpenRouter: {type(e).__name__}: {e}")

    key = str(body.get("key", "")).strip()
    if not key:
        die(f"no key in OpenRouter's response: {json.dumps(body)[:300]}")
    return key


PENDING_LOGIN = "login-pending.json"
PENDING_TTL = 900   # seconds; a half-finished login should not linger


def pending_path() -> Path:
    return USER_CONFIG.parent / PENDING_LOGIN


def save_pending(verifier: str) -> None:
    pending_path().parent.mkdir(parents=True, exist_ok=True)
    pending_path().write_text(
        json.dumps({"code_verifier": verifier, "at": time.time()}), encoding="utf-8")
    try:
        pending_path().chmod(0o600)
    except OSError:
        pass


def take_pending() -> str:
    path = pending_path()
    if not path.is_file():
        die("no login in progress. Start one with --login, approve in the "
            "browser, then pass the code back with --login --code ...")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        path.unlink(missing_ok=True)
        die("the pending login was unreadable. Run --login again.")
    path.unlink(missing_ok=True)
    if time.time() - float(data.get("at", 0)) > PENDING_TTL:
        die("that login attempt expired. Run --login again.")
    return str(data.get("code_verifier", ""))


def login_manually(timeout: int) -> int:
    """For a session whose browser is not on the user's machine.

    Nothing can listen on the user's localhost from here, so the callback is
    never delivered. The code still reaches them: OpenRouter redirects their
    browser to a localhost URL that fails to load, and the address bar holds it.
    """
    verifier, challenge = pkce_pair()
    save_pending(verifier)

    url = OPENROUTER_AUTH_URL + "?" + urllib.parse.urlencode({
        "callback_url": "http://localhost:8765/callback",
        "code_challenge": challenge,
        "code_challenge_method": "S256",
    })
    print("This session runs on a different machine from your browser, so the\n"
          "callback cannot reach it. Two steps instead:\n")
    print(f"1. Open this and approve:\n\n   {url}\n")
    print("2. Your browser will then fail to load a localhost page. That is\n"
          "   expected. Copy the code= value out of its address bar and run:\n")
    print("       /freshair --login --code PASTE_IT_HERE\n")
    print(f"(The attempt expires in {PENDING_TTL // 60} minutes.)")
    return 0


def finish_login(code: str, timeout: int) -> int:
    verifier = take_pending()
    key = exchange_code(code.strip(), verifier, timeout)
    path = write_user_config({"api_key": key})
    print(f"Connected. Key saved to {path} (mode 600); it was never displayed.")
    print("Try it:  /freshair --check")
    return 0


def openrouter_login(timeout: int, manual: bool = False) -> int:
    # A cloud or web session runs somewhere the user's browser cannot reach.
    if manual or os.environ.get("CLAUDE_CODE_REMOTE") or os.environ.get("SSH_CONNECTION"):
        return login_manually(timeout)

    verifier, challenge = pkce_pair()
    callback, (server, received) = await_oauth_code(timeout)

    url = OPENROUTER_AUTH_URL + "?" + urllib.parse.urlencode({
        "callback_url": callback,
        "code_challenge": challenge,
        "code_challenge_method": "S256",
    })

    opened = False
    try:
        opened = webbrowser.open(url)
    except Exception:  # noqa: BLE001 — a headless box has no browser
        opened = False

    print("Approve FreshAir in your browser." if opened else
          "Open this in a browser on THIS machine:")
    print(f"\n  {url}\n")
    if not opened:
        print("(No browser here. If this machine is not the one you are sitting\n"
              " at, stop and use:  --login --manual)\n")
    print(f"Waiting up to {timeout}s for the callback...", flush=True)

    server.handle_request()   # blocks until the browser calls back, or times out
    server.server_close()

    if received.get("error"):
        die(f"OpenRouter returned an error: {received['error']}")
    code = received.get("code", "")
    if not code:
        die("no authorization code came back — the browser never reached the "
            "callback, or it timed out. Nothing was saved.\n"
            "If your browser is on a different machine from this session, use:\n"
            "    --login --manual")

    key = exchange_code(code, verifier, timeout)
    path = write_user_config({"api_key": key})
    print(f"\nConnected. Key saved to {path} (mode 600); it was never displayed.")
    print("Try it:  freshair --check")
    return 0


def apply_profile(config: dict, name: str) -> dict:
    profiles = config.get("profiles") or {}
    if name not in profiles:
        known = ", ".join(profiles) or "(none defined)"
        die(f"no profile named {name!r}. Defined in {USER_CONFIG}: {known}")
    return profiles[name] or {}


def describe_config(cwd: Path, backends: dict) -> None:
    print("Config files, in order of precedence (later wins):")
    files = config_files(cwd)
    if not files:
        print(f"  (none) — --set-key or --save-default will create {USER_CONFIG}")
    for path, data in files:
        keys = ", ".join(k for k in data if k != "api_key")
        secret = " api_key=set" if data.get("api_key") else ""
        print(f"  {path}\n      {keys or '(empty)'}{secret}")

    config = load_config(cwd)
    print("\nResolved:")
    print(f"  backend  {config.get('backend', 'auto')}")
    print(f"  models   {', '.join(config.get('models') or DEFAULT_MODELS)}")
    print(f"  mode     {config.get('mode', 'fresh')}")

    key = openrouter_key(config)
    where = ("OPENROUTER_API_KEY" if os.environ.get("OPENROUTER_API_KEY", "").strip()
             else str(USER_CONFIG) if key else "not set")
    print(f"  api_key  {(key[:12] + '...') if key else '(none)'}  [{where}]")

    profiles = config.get("profiles") or {}
    print("\nProfiles:" if profiles else "\nProfiles: (none) — see --save-default")
    for name, body in profiles.items():
        bits = []
        if body.get("backend"):
            bits.append(f"backend={body['backend']}")
        if body.get("models"):
            bits.append("models=" + ",".join(body["models"]))
        print(f"  -p {name:<12} {'  '.join(bits)}")

    print("\nReachable right now: "
          + (", ".join(reachable_backends(backends, openrouter_key(config)))
             or "(nothing — see --check)"))


def main() -> None:
    cwd = Path(os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()).resolve()
    config = load_config(cwd)
    backends = resolve_backends(config)

    ap = argparse.ArgumentParser(
        prog="freshair",
        description="FreshAir — get an outside opinion from a model that has "
                    "not seen this conversation.",
    )
    ap.add_argument("focus", nargs="*",
                    help="what to look at, e.g. 'is the caching layer worth it'")
    ap.add_argument("--mode", choices=["fresh", "full"],
                    default=config.get("mode", "fresh"),
                    help="fresh (default): send only the goal and the current "
                         "state, so the reviewer cannot be anchored by the "
                         "reasoning that got you here. full: send the whole "
                         "transcript, for 'where exactly did we go wrong'.")
    ap.add_argument("--goal-turns", type=int, default=int(config.get("goal_turns", 0)),
                    help="in fresh mode, use only the first N human "
                         "instructions as the goal (0 = all of them)")
    ap.add_argument("-b", "--backend", action="append", default=[],
                    help="auto (default) | all | " + " | ".join(list(backends) + ["openrouter"])
                         + ". Repeat or comma-separate to ask several "
                           "independent reviewers at once; 'all' asks every one "
                           "this machine can reach. CLI backends use the login "
                           "you already have; openrouter needs OPENROUTER_API_KEY.")
    ap.add_argument("-m", "--model", action="append", default=[],
                    help="model id; repeat or comma-separate to run several in "
                         "parallel. Omit on a CLI backend to use its own "
                         "default. With more than one backend selected, model "
                         "ids are not portable between vendors, so these apply "
                         "to openrouter only and each CLI uses its own default.")
    ap.add_argument("--transcript", help="path to a session .jsonl (default: this session)")
    ap.add_argument("--session-id", help="session id to look up, if autodetection picks wrong")
    ap.add_argument("--from", dest="source", choices=["auto", "claude", "codex"],
                    default=config.get("from", "auto"),
                    help="which agent's session to review. auto (default) takes "
                         "the most recently written session for this directory, "
                         "whichever host wrote it.")
    ap.add_argument("--budget", type=int,
                    default=int(config.get("budget", DEFAULT_BUDGET)),
                    help=f"max transcript characters to send (default {DEFAULT_BUDGET})")
    ap.add_argument("--head-turns", type=int, default=int(config.get("head_turns", 6)),
                    help="opening turns always kept, so drift stays visible (default 6)")
    ap.add_argument("--thinking", action="store_true",
                    help="include the agent's thinking blocks")
    ap.add_argument("--no-diff", action="store_true", help="do not attach the git diff")
    ap.add_argument("--no-claim", action="store_true",
                    help="in fresh mode, withhold the agent's own account of "
                         "where things stand, leaving only the goal and the diff")
    ap.add_argument("--no-redact", action="store_true",
                    help="skip the credential scrub (not recommended)")
    ap.add_argument("--lang", default=config.get("lang", "English"),
                    help="language for the review (default English; set \"lang\" "
                         "in .freshair.json to change it permanently)")
    ap.add_argument("--temperature", type=float, default=float(config.get("temperature", 0.7)))
    ap.add_argument("--timeout", type=int, default=int(config.get("timeout", 600)))
    ap.add_argument("-p", "--profile",
                    help="use a saved profile (see --show-config for the list)")
    ap.add_argument("--save-default", nargs="?", const="", metavar="NAME",
                    help="remember this call's --backend/--model choice. Bare, "
                         "it becomes the default; with a NAME it becomes a "
                         "profile you select with -p NAME.")
    ap.add_argument("--manual", action="store_true",
                    help="with --login: print the URL and take the code back by "
                         "hand, for when your browser is on another machine")
    ap.add_argument("--code", metavar="CODE",
                    help="with --login: finish a --manual login using the code "
                         "from your browser's address bar")
    ap.add_argument("--login", action="store_true",
                    help="connect OpenRouter in the browser — you approve, the "
                         "key is stored here, you never see or paste it")
    ap.add_argument("--set-key", metavar="KEY",
                    help="store an OpenRouter key in the user config (mode 600) "
                         "so no environment variable is needed")
    ap.add_argument("--show-config", action="store_true",
                    help="print where every setting comes from, and what is "
                         "reachable right now")
    ap.add_argument("--check", action="store_true",
                    help="probe each backend with a one-token prompt and report "
                         "which ones actually work on this machine")
    ap.add_argument("--dry-run", action="store_true",
                    help="print exactly what would be sent and how, call nothing")
    ap.add_argument("--save", metavar="PATH", help="also write the review to this file")
    args = ap.parse_args()

    if args.login or args.code:
        if args.code:
            sys.exit(finish_login(args.code, args.timeout))
        sys.exit(openrouter_login(args.timeout, manual=args.manual))

    if args.set_key:
        path = write_user_config({"api_key": args.set_key.strip()})
        print(f"Stored OpenRouter key in {path} (mode 600).")
        print("Nothing else to do — it is picked up automatically. "
              "An OPENROUTER_API_KEY in the environment still wins if set.")
        return

    if args.save_default is not None:
        chosen_backends = [b.strip() for e in args.backend for b in e.split(",") if b.strip()]
        chosen_models = [m.strip() for e in args.model for m in e.split(",") if m.strip()]
        if not chosen_backends and not chosen_models:
            die("--save-default needs something to save: pass -b and/or -m "
                "alongside it, e.g. -b openrouter -m openai/gpt-5.1 --save-default")
        entry = {}
        if chosen_backends:
            entry["backend"] = ",".join(chosen_backends)
        if chosen_models:
            entry["models"] = chosen_models

        if args.save_default:                      # a named profile
            existing = load_config(cwd).get("profiles") or {}
            existing[args.save_default] = entry
            path = write_user_config({"profiles": existing})
            print(f"Saved profile {args.save_default!r} in {path}.")
            print(f"Use it with:  /freshair -p {args.save_default}")
        else:                                      # the default for every call
            path = write_user_config(entry)
            print(f"Saved as the default in {path}: "
                  + "  ".join(f"{k}={v}" for k, v in entry.items()))
            print("Use it with:  /freshair")
        return

    if args.show_config:
        describe_config(cwd, backends)
        return

    if args.check:
        asked = [b.strip() for entry in args.backend for b in entry.split(",") if b.strip()]
        selected = ([b for b in asked if b not in ("auto", "all")]
                    or list(backends) + ["openrouter"])
        print("Probing backends (a real call each, one token of output):")
        sys.exit(1 if check_backends(backends, selected, config, args.timeout, cwd) else 0)

    profile = apply_profile(config, args.profile) if args.profile else {}
    api_key = openrouter_key(config)

    requested: list[str] = []
    for entry in (args.backend
                  or ([profile["backend"]] if profile.get("backend") else None)
                  or [config.get("backend", "auto")]):
        requested.extend(b.strip() for b in entry.split(",") if b.strip())

    selected: list[str] = []
    for name in requested:
        if name == "auto":
            selected.append(detect_backend(backends, api_key))
        elif name == "all":
            # Every independent reviewer this machine can actually reach.
            selected.extend(reachable_backends(backends, api_key))
        elif name == "openrouter" or name in backends:
            selected.append(name)
        else:
            die(f"unknown backend {name!r}. Known: "
                + ", ".join(list(backends) + ["openrouter", "auto", "all"]))

    selected = list(dict.fromkeys(selected))  # keep order, drop repeats
    if not selected:
        die("no backend available. Install and sign in to codex or gemini, "
            "or set OPENROUTER_API_KEY.")

    any_cli = any(b != "openrouter" for b in selected)

    asked_models: list[str] = []
    for entry in (args.model or profile.get("models") or []):
        asked_models.extend(m.strip() for m in entry.split(",") if m.strip())

    def models_for(name: str) -> list[str | None]:
        if name == "openrouter":
            return list(asked_models or profile.get("models")
                        or config.get("models") or DEFAULT_MODELS)
        # Model ids are not portable between vendors, so an explicit -m only
        # reaches a CLI backend when it is the only one running.
        if asked_models and len(selected) == 1:
            return list(asked_models)
        return list(backends[name].get("models") or []) or [None]

    jobs: list[tuple[str, str | None]] = [
        (name, model) for name in selected for model in models_for(name)
    ]

    # ---- build the payload ------------------------------------------------
    path, source = find_transcript(args.transcript, cwd, args.session_id, args.source)
    turns = parse_transcript(path, keep_thinking=args.thinking, source=source)
    if not turns:
        die(f"no readable turns in {path}")

    repo_block, diff_block = ("", "")
    if not args.no_diff:
        repo_block, diff_block = repo_context(cwd)

    focus_block = ""
    focus = " ".join(args.focus).strip()
    if focus:
        focus_block = f"The human specifically wants your read on: {focus}\n\n"

    def system_for(name: str) -> str:
        rule = VERIFY_RULE_API if name == "openrouter" else VERIFY_RULE_CLI
        template = SYSTEM_PROMPT_FRESH if args.mode == "fresh" else SYSTEM_PROMPT_FULL
        return template.format(verify_rule=rule)

    verify_rule = VERIFY_RULE_CLI if any_cli else VERIFY_RULE_API

    if args.mode == "fresh":
        goal = extract_goal(turns, args.goal_turns, args.budget)
        claim = "" if args.no_claim else extract_claim(turns)
        claim_block = ""
        if claim:
            claim_block = (
                "\n===== THE AGENT'S OWN ACCOUNT OF WHERE THIS STANDS =====\n"
                "(A claim, not evidence. Check it against the diff above.)\n\n"
                f"{claim}\n"
                "===== END ACCOUNT =====\n"
            )
        if not diff_block and not repo_block:
            claim_block += (
                "\n(No git repository here, so there is no diff to check the "
                "account against.)\n"
            )

        goal, diff_block, claim_block = fit_fresh(
            goal, repo_block, diff_block, claim_block, args.budget)

        system_msg = SYSTEM_PROMPT_FRESH.format(verify_rule=verify_rule)
        user_msg = USER_TEMPLATE_FRESH.format(
            focus_block=focus_block,
            goal=goal,
            repo_block=repo_block,
            diff_block=diff_block,
            claim_block=claim_block,
            lang=args.lang,
        )
        shown = len(goal_instructions(turns, args.goal_turns))
        stats = {"total_turns": len(turns), "kept_turns": shown,
                 "elided_turns": len(turns) - shown}
        shape = (f"goal: {shown} human instruction(s) + current state; "
                 f"{len(turns) - shown} turns of agent reasoning withheld")
    else:
        transcript, stats = fit_to_budget(turns, args.budget, args.head_turns)
        system_msg = SYSTEM_PROMPT_FULL.format(verify_rule=verify_rule)
        user_msg = USER_TEMPLATE_FULL.format(
            focus_block=focus_block,
            repo_block=repo_block,
            transcript=transcript,
            diff_block=diff_block,
            lang=args.lang,
        )
        shape = (f"turns: {stats['kept_turns']}/{stats['total_turns']} kept"
                 + (f", {stats['elided_turns']} elided from the middle"
                    if stats["elided_turns"] else ""))

    redacted_count = 0
    if not args.no_redact:
        user_msg, redacted_count = redact(user_msg)

    def route_for(name: str) -> str:
        if name == "openrouter":
            return "OpenRouter API"
        return (f"{backends[name].get('label', name)} — local CLI, your own "
                f"login, nothing routed through a third party")

    route = " + ".join(route_for(n) for n in selected)

    vendors = {("openrouter" if n == "openrouter" else backends[n].get("vendor"))
               for n in selected}
    warning = ""
    if not [v for v in vendors if v != HOST_VENDOR]:
        # Escaping the context is the main mechanism and it is doing the work
        # here; a different vendor is an increment on top, not the pass mark.
        # Overstating that drives people to skip the tool over setup friction.
        warning = (
            f"\nNote: same vendor as the agent you are talking to "
            f"({', '.join(selected)}). The fresh context is the main mechanism "
            "and it is working — that alone finds most of what this tool finds. "
            "A different vendor additionally covers mistakes both models would "
            "make; install codex or gemini if you want that too.\n"
        )
    elif len(vendors) == 1:
        warning = (
            "\n(One reviewer. Two that never saw each other's answer disagree "
            "in the places worth looking — try --backend all.)\n"
        )

    header = (
        f"transcript: {path}  ({SESSION_SOURCES[source]['label']})\n"
        f"mode: {args.mode}\n"
        f"{shape}\n"
        f"payload: {len(user_msg):,} chars (~{len(user_msg)//4:,} tokens)\n"
        f"backend: {route}\n"
        + "reviewers: "
        + ", ".join(f"{b}" + (f" · {m}" if m else "") for b, m in jobs) + "\n"
        + (f"redacted: {redacted_count} credential-shaped strings\n" if redacted_count else "")
        + warning
    )

    if args.dry_run:
        print(header)
        for name, m in jobs:
            if name == "openrouter":
                print(f"would POST to OpenRouter as {m}")
            else:
                print("would run: " + " ".join(cli_command(backends[name], m, cwd))
                      + "\n           (prompt on stdin, from a scratch cwd)")
        print()
        print("=" * 70)
        print("SYSTEM:\n" + system_msg)
        print("=" * 70)
        print("USER:\n" + user_msg)
        return

    # ---- dispatch ---------------------------------------------------------
    for name in selected:
        if name == "openrouter":
            if not api_key:
                die("No OpenRouter key. Either store one with\n"
                    "    freshair --set-key sk-or-v1-...\n"
                    "(get it at https://openrouter.ai/keys), or use a CLI you "
                    "are already signed in to: --backend codex | gemini | claude")
        elif not shutil.which(backends[name]["cmd"][0]):
            die(f"backend {name!r} needs {backends[name]['cmd'][0]!r} on PATH, "
                f"and it is not there.\nInstall and sign in to it, pick another "
                f"with --backend, or use --backend openrouter.")

    def run(job: tuple[str, str | None]) -> dict:
        name, model = job
        if name == "openrouter":
            r = ask_openrouter(model, system_for(name), user_msg, api_key,
                               args.temperature, args.timeout)
        else:
            r = ask_cli(name, backends[name], model, system_for(name),
                        user_msg, args.timeout, cwd)
        r["backend"] = name
        return r

    print(header, file=sys.stderr)

    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, len(jobs))) as pool:
        results = list(pool.map(run, jobs))

    # ---- report -----------------------------------------------------------
    def reviewer(r: dict) -> str:
        name = r.get("backend", "")
        model = r.get("model", "")
        return model if model.startswith(name) else f"{name} · {model}" if name else model

    provenance = warning.strip()
    chunks = [f"<!-- {OUTPUT_MARKER} -->\n" + f"# Outside opinion\n\n_{datetime.now(timezone.utc).astimezone():%Y-%m-%d %H:%M} · via {route}_\n"
              + (f"\n> {provenance}\n" if provenance else "")]
    failures = 0
    for r in results:
        if r.get("error"):
            failures += 1
            chunks.append(f"\n---\n\n## ❌ {reviewer(r)}\n\n```\n{r['error']}\n```\n")
            continue
        usage = r.get("usage") or {}
        meta = f"{r['seconds']}s"
        if usage.get("total_tokens"):
            meta += f" · {usage['total_tokens']:,} tokens"
        chunks.append(f"\n---\n\n## 🔎 {reviewer(r)}\n\n_{meta}_\n\n{r['text']}\n")

    if len([r for r in results if not r.get("error")]) > 1:
        chunks.append(
            "\n---\n\n## Reading several reviewers\n\n"
            "These reviewers never saw each other's answers. Where two of them "
            "independently land on the same problem, that is the strongest "
            "signal available here. Where only one raises something, it is a "
            "lead, not a finding. Where they contradict each other, the "
            "disagreement itself is usually the interesting part.\n"
        )

    out = "".join(chunks)
    print(out)

    if args.save:
        Path(args.save).expanduser().write_text(out, encoding="utf-8")
        print(f"\nsaved to {args.save}", file=sys.stderr)

    if failures == len(results):
        sys.exit(1)


if __name__ == "__main__":
    main()
