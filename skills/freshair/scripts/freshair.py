def cli_command(spec: dict, model: str | None, repo: Path | None = None) -> list[str]:
    """Flags first, then the model, then whatever must stay last — a stdin
    sentinel or a variadic list that would otherwise swallow what follows."""
    cmd = list(spec["cmd"])
    if repo and spec.get("dir_flag"):
        cmd += [spec["dir_flag"], str(repo)]
    if model and spec.get("model_flag"):
        cmd += [spec["model_flag"], model]
    return cmd + list(spec.get("tail") or [])


# Variables that tell a nested agent CLI which session it belongs to. Leaving
# them set makes the child append its own prompt to *this* session's transcript,
# which is the file we are reviewing. Auth-bearing variables are deliberately
# left alone.
CHILD_ENV_STRIP = (
    "CLAUDE_CODE_SESSION_ID",
    "CLAUDE_SESSION_ID",
    "CLAUDE_CODE_CHILD_SESSION",
    "CLAUDE_PROJECT_DIR",
    "CLAUDE_CODE_ENTRYPOINT",
    "CLAUDE_AFTER_LAST_COMPACT",
    "CLAUDE_CODE_DIAGNOSTICS_FILE",
)


def child_env() -> dict:
    env = dict(os.environ)
    for key in CHILD_ENV_STRIP:
        env.pop(key, None)
    return env


def ask_cli(backend: str, spec: dict, model: str | None, system: str, user: str,
            timeout: int, repo: Path) -> dict:
    """Run the reviewer outside the repository.

    An agent CLI files its session log under a directory derived from its
    working directory. Started inside the repo, the reviewer's own prompt lands
    in the very transcript we read — so the next review takes the last review as
    input. Running it from a scratch directory puts that log somewhere harmless,
    and `dir_flag` hands the repo back as readable.
    """
    cmd = cli_command(spec, model, repo)
    name = f"{backend}" + (f" · {model}" if model else "")

    started = time.time()
    try:
        with tempfile.TemporaryDirectory(prefix="freshair-") as scratch:
            proc = subprocess.run(
                cmd,
                input=f"{system}\n\n{user}",
                capture_output=True,
                text=True,
                timeout=timeout,
                cwd=scratch,
                env=child_env(),
            )
    except FileNotFoundError:
        return {"model": name, "error": f"{spec['cmd'][0]} is not installed or not on PATH"}
    except subprocess.TimeoutExpired:
        return {"model": name, "error": f"timed out after {timeout}s"}
    except OSError as e:
        return {"model": name, "error": f"{type(e).__name__}: {e}"}

    out = (proc.stdout or "").strip()
    if proc.returncode != 0 and not out:
        err = (proc.stderr or "").strip()[:800] or f"exit code {proc.returncode}"
        return {
            "model": name,
            "error": f"{' '.join(cmd)}\n{err}\n\n"
                     f"If this backend's flags have changed upstream, override "
                     f"them in .freshair.json under backends.{backend}.cmd",
        }
    if not out:
        return {"model": name, "error": f"{' '.join(cmd)} produced no output"}

    return {"model": name, "text": out, "usage": {}, "seconds": round(time.time() - started, 1)}


PROBE_PROMPT = "Reply with exactly this token and nothing else: FRESHAIR-OK"
PROBE_TOKEN = "FRESHAIR-OK"


def check_backends(backends: dict[str, dict], selected: list[str],
                   config: dict, timeout: int, repo: Path) -> int:
    """Actually call each backend with a one-token prompt.

    The command lines here are built from each vendor's documented flags, and
    vendors change flags. This turns "should work" into something the user can
    confirm on their own machine in a few seconds.
    """
    failures = 0

    # The in-progress line only makes sense on a terminal; carriage returns do
    # not overwrite anything in a pipe or a log file.
    live = sys.stdout.isatty()

    def progress(line: str) -> None:
        if live:
            print(line, end="\r", flush=True)

    def emit(line: str) -> None:
        print(("\r" + " " * 60 + "\r" if live else "") + line)

    for name in selected:
        if name == "openrouter":
            key = openrouter_key(config)
            if not key:
                emit("  ✗ openrouter — no key; run --set-key sk-or-v1-...")
                failures += 1
                continue
            model = (config.get("models") or DEFAULT_MODELS)[0]
            progress(f"  … openrouter ({model})")
            r = ask_openrouter(model, "", PROBE_PROMPT, key, 0.0, timeout)
            label = f"openrouter ({model})"
        else:
            spec = backends[name]
            binary = spec["cmd"][0]
            if not shutil.which(binary):
                emit(f"  – {name:<11} not installed ({binary} not on PATH)")
                continue
            cmd = " ".join(cli_command(spec, None, repo))
            progress(f"  … {name}")
            r = ask_cli(name, spec, None, "", PROBE_PROMPT, timeout, repo)
            label = f"{name:<11} {cmd}"

        if r.get("error"):
            emit(f"  ✗ {label}\n      {r['error'].splitlines()[0]}")
            failures += 1
        elif PROBE_TOKEN not in (r.get("text") or ""):
            emit(f"  ✗ {label}\n      responded, but not with the probe token: "
                 f"{(r.get('text') or '')[:120]!r}")
            failures += 1
        else:
            emit(f"  ✓ {label}   ({r['seconds']}s)")

    return failures


def resolve_backends(config: dict) -> dict[str, dict]:
    """Built-in CLI backends, with per-repo overrides layered on top."""
    merged = {k: dict(v) for k, v in CLI_BACKENDS.items()}
    for name, override in (config.get("backends") or {}).items():
        merged.setdefault(name, {"label": name, "vendor": name})
        merged[name].update(override)
    return merged


def reachable_backends(backends: dict[str, dict], api_key: str = "") -> list[str]:
    """Every reviewer this machine can actually reach, outsiders first.

    Independent reviewers that never saw each other's answers are the point:
    where two of them converge is worth much more than either one alone.
    """
    order = [b for b in AUTO_ORDER if b in backends]
    order += [b for b in backends if b not in order]
    found = [n for n in order if shutil.which(backends[n]["cmd"][0])]
    if api_key or os.environ.get("OPENROUTER_API_KEY", "").strip():
        found.append("openrouter")
    return found


def detect_backend(backends: dict[str, dict], api_key: str = "") -> str:
    """Pick a backend the user is already signed in to, outsiders first."""
    order = [b for b in AUTO_ORDER if b in backends]
    order += [b for b in backends if b not in order]

    non_anthropic = [b for b in order if backends[b].get("vendor") != "anthropic"]
    for name in non_anthropic:
        if shutil.which(backends[name]["cmd"][0]):
            return name

    if api_key or os.environ.get("OPENROUTER_API_KEY", "").strip():
        return "openrouter"

    for name in order:
        if shutil.which(backends[name]["cmd"][0]):
            return name

    return "openrouter"


