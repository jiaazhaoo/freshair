def render_turns(turns: list[dict]) -> str:
    out = []
    for i, t in enumerate(turns, 1):
        who = {"user": "HUMAN", "assistant": "AGENT"}.get(t["role"], "TOOL OUTPUT")
        out.append(f"--- turn {i} · {who} ---\n{t['text']}")
    return "\n\n".join(out)


def fit_to_budget(turns: list[dict], budget: int, head_turns: int) -> tuple[str, dict]:
    """
    Keep the opening turns (the original goal — the single most important thing
    for spotting drift) and as many recent turns as fit. Elide the middle.
    """
    stats = {"total_turns": len(turns), "kept_turns": len(turns), "elided_turns": 0}

    full = render_turns(turns)
    if len(full) <= budget:
        return full, stats

    head = turns[:head_turns]
    head_text = render_turns(head)
    if len(head_text) > budget:
        # Pathological case: the opening turns alone blow the budget. Keep the
        # original ask visible rather than dropping it.
        stats["kept_turns"] = len(head)
        stats["elided_turns"] = len(turns) - len(head)
        return clip(head_text, budget), stats

    tail: list[dict] = []
    used = len(head_text)
    for t in reversed(turns[head_turns:]):
        chunk = len(t["text"]) + 40
        if used + chunk > budget:
            break
        tail.append(t)
        used += chunk
    tail.reverse()

    elided = len(turns) - len(head) - len(tail)
    stats["kept_turns"] = len(head) + len(tail)
    stats["elided_turns"] = elided

    gap = (
        f"\n\n--- [{elided} turns from the middle of the session were elided to fit; "
        f"the opening and the most recent work are both intact] ---\n\n"
    )
    return head_text + gap + render_turns(tail), stats


GOAL_TURN_CAP = 6_000
CLAIM_CAP = 4_000


# Continuations the harness injects as user turns. They carry no requirement,
# and listing them as goals dilutes the real ones.
BOILERPLATE = {
    "continue from where you left off.",
    "continue",
    "continue.",
    "go on",
    "keep going",
    "please continue",
}


# Harness notices delivered as user turns — "[Request interrupted by user]" and
# friends. They report on the session, they do not ask for anything.
HARNESS_NOTICE = re.compile(r"^\[[^\]\n]{0,120}\]$")


def goal_instructions(turns: list[dict], goal_turns: int) -> list[str]:
    """What the human actually asked for, and nothing the agent said back.

    The human's messages are the requirements. The agent's are where the
    rationalization lives, which is the whole thing we are trying not to ship.
    """
    texts = []
    for turn in turns:
        if turn["role"] != "user":
            continue
        text = turn["text"].strip()
        if not text or text.lower() in BOILERPLATE or HARNESS_NOTICE.match(text):
            continue
        # An instruction cut off mid-send and retyped supersedes the fragment it
        # extends; listing both reads as two separate requirements.
        if texts and text.startswith(texts[-1]):
            texts[-1] = text
        else:
            texts.append(text)
    return texts[:goal_turns] if goal_turns > 0 else texts


def extract_goal(turns: list[dict], goal_turns: int) -> str:
    kept = goal_instructions(turns, goal_turns)
    if not kept:
        return "(no human instructions found in this session)"
    return "\n\n".join(
        f"--- instruction {i} ---\n{clip(text, GOAL_TURN_CAP)}"
        for i, text in enumerate(kept, 1)
    )


def extract_claim(turns: list[dict]) -> str:
    """The agent's most recent account of where things stand.

    Included as a claim to be checked against the diff, not as evidence. Tool
    invocations are stripped — what is wanted is the self-report, not the log.
    """
    for turn in reversed(turns):
        if turn["role"] != "assistant":
            continue
        prose = [ln for ln in turn["text"].splitlines()
                 if not ln.startswith("[tool")]
        text = "\n".join(prose).strip()
        if text:
            return clip(text, CLAIM_CAP)
    return ""


