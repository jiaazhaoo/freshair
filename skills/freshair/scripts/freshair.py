def ask_openrouter(model: str, system: str, user: str, api_key: str,
                   temperature: float, timeout: int) -> dict:
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
        "temperature": temperature,
    }
    req = urllib.request.Request(
        OPENROUTER_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            # OpenRouter shows these on the user's activity page. The referer
            # is the repository, which is still named what-do-you-think; the
            # title is the tool.
            "HTTP-Referer": "https://github.com/jiaazhaoo/what-do-you-think",
            "X-Title": "FreshAir",
        },
        method="POST",
    )

    started = time.time()
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        detail = e.read().decode("utf-8", "replace")[:600]
        return {"model": model, "error": f"HTTP {e.code}: {detail}"}
    except Exception as e:  # noqa: BLE001 — surface anything the network does
        return {"model": model, "error": f"{type(e).__name__}: {e}"}

    choices = body.get("choices") or []
    if not choices:
        return {"model": model, "error": f"no choices in response: {json.dumps(body)[:600]}"}

    return {
        "model": model,
        "text": (choices[0].get("message") or {}).get("content", "").strip(),
        "usage": body.get("usage") or {},
        "seconds": round(time.time() - started, 1),
    }


# --------------------------------------------------------------------------
# calling a locally installed, already-signed-in vendor CLI
# --------------------------------------------------------------------------

def cli_command(spec: dict, model: str | None, repo: Path | None = None) -> list[str]:
    """Flags first, then the model, then whatever must stay last — a stdin
    sentinel or a variadic list that would otherwise swallow what follows."""
    cmd = list(spec["cmd"])
    if repo and spec.get("dir_flag"):
        cmd += [spec["dir_flag"], str(repo)]
    if model and spec.get("model_flag"):
        cmd += [spec["model_flag"], model]
    return cmd + list(spec.get("tail") or [])


# Variables that tell a nested agent CLI which session it belongs to. Leaving
# them set makes the child append its own prompt to *this* session's transcript,
# which is the file we are reviewing. Auth-bearing variables are deliberately
# left alone.
CHILD_ENV_STRIP = (
    "CLAUDE_CODE_SESSION_ID",
    "CLAUDE_SESSION_ID",
    "CLAUDE_CODE_CHILD_SESSION",
    "CLAUDE_PROJECT_DIR",
    "CLAUDE_CODE_ENTRYPOINT",
    "CLAUDE_AFTER_LAST_COMPACT",
    "CLAUDE_CODE_DIAGNOSTICS_FILE",
)


def child_env() -> dict:
    env = dict(os.environ)
    for key in CHILD_ENV_STRIP:
        env.pop(key, None)
    return env


def ask_cli(backend: str, spec: dict, model: str | None, system: str, user: str,
            timeout: int, repo: Path) -> dict:
    """Run the reviewer outside the repository.

    An agent CLI files its session log under a directory derived from its
    working directory. Started inside the repo, the reviewer's own prompt lands
    in the very transcript we read — so the next review takes the last review as
    input. Running it from a scratch directory puts that log somewhere harmless,
    and `dir_flag` hands the repo back as readable.
    """
    cmd = cli_command(spec, model, repo)
    name = f"{backend}" + (f" · {model}" if model else "")

    started = time.time()
    try:
        with tempfile.TemporaryDirectory(prefix="freshair-") as scratch:
            proc = subprocess.run(
                cmd,
                input=f"{system}\n\n{user}",
                capture_output=True,
                text=True,
                timeout=timeout,
                cwd=scratch,
                env=child_env(),
            )
    except FileNotFoundError:
        return {"model": name, "error": f"{spec['cmd'][0]} is not installed or not on PATH"}
    except subprocess.TimeoutExpired:
        return {"model": name, "error": f"timed out after {timeout}s"}
    except OSError as e:
        return {"model": name, "error": f"{type(e).__name__}: {e}"}

    out = (proc.stdout or "").strip()
    if proc.returncode != 0 and not out:
        err = (proc.stderr or "").strip()[:800] or f"exit code {proc.returncode}"
        return {
            "model": name,
            "error": f"{' '.join(cmd)}\n{err}\n\n"
                     f"If this backend's flags have changed upstream, override "
                     f"them in .freshair.json under backends.{backend}.cmd",
        }
    if not out:
        return {"model": name, "error": f"{' '.join(cmd)} produced no output"}

    return {"model": name, "text": out, "usage": {}, "seconds": round(time.time() - started, 1)}


PROBE_PROMPT = "Reply with exactly this token and nothing else: FRESHAIR-OK"
PROBE_TOKEN = "FRESHAIR-OK"


def check_backends(backends: dict[str, dict], selected: list[str],
                   config: dict, timeout: int, repo: Path) -> int:
    """Actually call each backend with a one-token prompt.

    The command lines here are built from each vendor's documented flags, and
    vendors change flags. This turns "should work" into something the user can
    confirm on their own machine in a few seconds.
    """
    failures = 0

    # The in-progress line only makes sense on a terminal; carriage returns do
    # not overwrite anything in a pipe or a log file.
    live = sys.stdout.isatty()

    def progress(line: str) -> None:
        if live:
            print(line, end="\r", flush=True)

    def emit(line: str) -> None:
        print(("\r" + " " * 60 + "\r" if live else "") + line)

    for name in selected:
        if name == "openrouter":
            key = os.environ.get("OPENROUTER_API_KEY", "").strip()
            if not key:
                emit("  ✗ openrouter — OPENROUTER_API_KEY is not set")
                failures += 1
                continue
            model = (config.get("models") or DEFAULT_MODELS)[0]
            progress(f"  … openrouter ({model})")
            r = ask_openrouter(model, "", PROBE_PROMPT, key, 0.0, timeout)
            label = f"openrouter ({model})"
        else:
            spec = backends[name]
            binary = spec["cmd"][0]
            if not shutil.which(binary):
                emit(f"  – {name:<11} not installed ({binary} not on PATH)")
                continue
            cmd = " ".join(cli_command(spec, None, repo))
            progress(f"  … {name}")
            r = ask_cli(name, spec, None, "", PROBE_PROMPT, timeout, repo)
            label = f"{name:<11} {cmd}"

        if r.get("error"):
            emit(f"  ✗ {label}\n      {r['error'].splitlines()[0]}")
            failures += 1
        elif PROBE_TOKEN not in (r.get("text") or ""):
            emit(f"  ✗ {label}\n      responded, but not with the probe token: "
                 f"{(r.get('text') or '')[:120]!r}")
            failures += 1
        else:
            emit(f"  ✓ {label}   ({r['seconds']}s)")

    return failures


def resolve_backends(config: dict) -> dict[str, dict]:
    """Built-in CLI backends, with per-repo overrides layered on top."""
    merged = {k: dict(v) for k, v in CLI_BACKENDS.items()}
    for name, override in (config.get("backends") or {}).items():
        merged.setdefault(name, {"label": name, "vendor": name})
        merged[name].update(override)
    return merged


def detect_backend(backends: dict[str, dict]) -> str:
    """Pick a backend the user is already signed in to, outsiders first."""
    order = [b for b in AUTO_ORDER if b in backends]
    order += [b for b in backends if b not in order]

    non_anthropic = [b for b in order if backends[b].get("vendor") != "anthropic"]
    for name in non_anthropic:
        if shutil.which(backends[name]["cmd"][0]):
            return name

    if os.environ.get("OPENROUTER_API_KEY", "").strip():
        return "openrouter"

    for name in order:
        if shutil.which(backends[name]["cmd"][0]):
            return name

    return "openrouter"


# --------------------------------------------------------------------------

def die(msg: str) -> None:
    print(f"freshair: {msg}", file=sys.stderr)
    sys.exit(1)


def load_config(cwd: Path) -> dict:
    for path in (cwd / ".freshair.json",
                 Path.home() / ".config" / "freshair" / "config.json",
                 cwd / ".wdyt.json",                              # pre-rename names
                 Path.home() / ".config" / "wdyt" / "config.json"):
        if path.is_file():
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                print(f"freshair: ignoring malformed config at {path}", file=sys.stderr)
    return {}


def main() -> None:
    cwd = Path(os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()).resolve()
    config = load_config(cwd)
    backends = resolve_backends(config)

    ap = argparse.ArgumentParser(
        prog="freshair",
        description="FreshAir — get an outside opinion from a model that has "
                    "not seen this conversation.",
    )
    ap.add_argument("focus", nargs="*",
                    help="what to look at, e.g. 'is the caching layer worth it'")
    ap.add_argument("--mode", choices=["fresh", "full"],
                    default=config.get("mode", "fresh"),
                    help="fresh (default): send only the goal and the current "
                         "state, so the reviewer cannot be anchored by the "
                         "reasoning that got you here. full: send the whole "
                         "transcript, for 'where exactly did we go wrong'.")
    ap.add_argument("--goal-turns", type=int, default=int(config.get("goal_turns", 0)),
                    help="in fresh mode, use only the first N human "
                         "instructions as the goal (0 = all of them)")
    ap.add_argument("-b", "--backend",
                    default=config.get("backend", "auto"),
                    help="auto (default) | " + " | ".join(list(backends) + ["openrouter"])
                         + ". CLI backends use the login you already have; "
                           "openrouter needs OPENROUTER_API_KEY.")
    ap.add_argument("-m", "--model", action="append", default=[],
                    help="model id; repeat or comma-separate to run several in "
                         "parallel. Omit on a CLI backend to use its own default.")
    ap.add_argument("--transcript", help="path to a session .jsonl (default: this session)")
    ap.add_argument("--session-id", help="session id to look up, if autodetection picks wrong")
    ap.add_argument("--budget", type=int,
                    default=int(config.get("budget", DEFAULT_BUDGET)),
                    help=f"max transcript characters to send (default {DEFAULT_BUDGET})")
    ap.add_argument("--head-turns", type=int, default=int(config.get("head_turns", 6)),
                    help="opening turns always kept, so drift stays visible (default 6)")
    ap.add_argument("--thinking", action="store_true",
                    help="include the agent's thinking blocks")
    ap.add_argument("--no-diff", action="store_true", help="do not attach the git diff")
    ap.add_argument("--no-claim", action="store_true",
                    help="in fresh mode, withhold the agent's own account of "
                         "where things stand, leaving only the goal and the diff")
    ap.add_argument("--no-redact", action="store_true",
                    help="skip the credential scrub (not recommended)")
    ap.add_argument("--lang", default=config.get("lang", "the language the human used in the transcript"),
                    help="language for the review")
    ap.add_argument("--temperature", type=float, default=float(config.get("temperature", 0.7)))
    ap.add_argument("--timeout", type=int, default=int(config.get("timeout", 600)))
    ap.add_argument("--check", action="store_true",
                    help="probe each backend with a one-token prompt and report "
                         "which ones actually work on this machine")
    ap.add_argument("--dry-run", action="store_true",
                    help="print exactly what would be sent and how, call nothing")
    ap.add_argument("--save", metavar="PATH", help="also write the review to this file")
    args = ap.parse_args()

    if args.check:
        selected = ([args.backend] if args.backend not in ("auto", None)
                    else list(backends) + ["openrouter"])
        print("Probing backends (a real call each, one token of output):")
        sys.exit(1 if check_backends(backends, selected, config, args.timeout, cwd) else 0)

    backend = args.backend
    if backend == "auto":
        backend = detect_backend(backends)
    if backend != "openrouter" and backend not in backends:
        die(f"unknown backend {backend!r}. Known: "
            + ", ".join(list(backends) + ["openrouter", "auto"]))

    is_cli = backend != "openrouter"

    models: list[str | None] = []
    for entry in args.model:
        models.extend(m.strip() for m in entry.split(",") if m.strip())
    if not models:
        if is_cli:
            configured = backends[backend].get("models") or []
            models = list(configured) or [None]   # None = let the CLI choose
        else:
            models = list(config.get("models") or DEFAULT_MODELS)

    # ---- build the payload ------------------------------------------------
    path = find_transcript(args.transcript, cwd, args.session_id)
    turns = parse_transcript(path, keep_thinking=args.thinking)
    if not turns:
        die(f"no readable turns in {path}")

    repo_block, diff_block = ("", "")
    if not args.no_diff:
        repo_block, diff_block = repo_context(cwd)

    focus_block = ""
    focus = " ".join(args.focus).strip()
    if focus:
        focus_block = f"The human specifically wants your read on: {focus}\n\n"

    verify_rule = VERIFY_RULE_CLI if is_cli else VERIFY_RULE_API

    if args.mode == "fresh":
        goal = extract_goal(turns, args.goal_turns)
        claim = "" if args.no_claim else extract_claim(turns)
        claim_block = ""
        if claim:
            claim_block = (
                "\n===== THE AGENT'S OWN ACCOUNT OF WHERE THIS STANDS =====\n"
                "(A claim, not evidence. Check it against the diff above.)\n\n"
                f"{claim}\n"
                "===== END ACCOUNT =====\n"
            )
        if not diff_block and not repo_block:
            claim_block += (
                "\n(No git repository here, so there is no diff to check the "
                "account against.)\n"
            )

        system_msg = SYSTEM_PROMPT_FRESH.format(verify_rule=verify_rule)
        user_msg = USER_TEMPLATE_FRESH.format(
            focus_block=focus_block,
            goal=goal,
            repo_block=repo_block,
            diff_block=diff_block,
            claim_block=claim_block,
            lang=args.lang,
        )
        shown = len(goal_instructions(turns, args.goal_turns))
        stats = {"total_turns": len(turns), "kept_turns": shown,
                 "elided_turns": len(turns) - shown}
        shape = (f"goal: {shown} human instruction(s) + current state; "
                 f"{len(turns) - shown} turns of agent reasoning withheld")
    else:
        transcript, stats = fit_to_budget(turns, args.budget, args.head_turns)
        system_msg = SYSTEM_PROMPT_FULL.format(verify_rule=verify_rule)
        user_msg = USER_TEMPLATE_FULL.format(
            focus_block=focus_block,
            repo_block=repo_block,
            transcript=transcript,
            diff_block=diff_block,
            lang=args.lang,
        )
        shape = (f"turns: {stats['kept_turns']}/{stats['total_turns']} kept"
                 + (f", {stats['elided_turns']} elided from the middle"
                    if stats["elided_turns"] else ""))

    redacted_count = 0
    if not args.no_redact:
        user_msg, redacted_count = redact(user_msg)

    if is_cli:
        route = (f"{backends[backend].get('label', backend)} — local CLI, "
                 f"your own login, nothing routed through a third party")
    else:
        route = "OpenRouter API"

    same_vendor = is_cli and HOST_VENDOR and backends[backend].get("vendor") == HOST_VENDOR
    warning = ""
    if same_vendor:
        warning = (
            f"\n⚠️  {backend} is the same vendor as the agent you are already "
            "talking to. A fresh context window helps, but shared weights mean "
            "shared blind spots — this is the weak version of a second opinion.\n"
            "    For a real outsider: install and sign in to codex or gemini, "
            "or use --backend openrouter.\n"
        )

    header = (
        f"transcript: {path}\n"
        f"mode: {args.mode}\n"
        f"{shape}\n"
        f"payload: {len(user_msg):,} chars (~{len(user_msg)//4:,} tokens)\n"
        f"backend: {route}\n"
        f"models: {', '.join(m or '(backend default)' for m in models)}\n"
        + (f"redacted: {redacted_count} credential-shaped strings\n" if redacted_count else "")
        + warning
    )

    if args.dry_run:
        print(header)
        if is_cli:
            for m in models:
                print("would run: " + " ".join(cli_command(backends[backend], m, cwd))
                      + "\n           (prompt on stdin, from a scratch cwd)")
            print()
        print("=" * 70)
        print("SYSTEM:\n" + system_msg)
        print("=" * 70)
        print("USER:\n" + user_msg)
        return

    # ---- dispatch ---------------------------------------------------------
    if is_cli:
        binary = backends[backend]["cmd"][0]
        if not shutil.which(binary):
            die(f"backend {backend!r} needs {binary!r} on PATH, and it is not there.\n"
                f"Install and sign in to it, pick another with --backend, "
                f"or use --backend openrouter.")
        run = lambda m: ask_cli(backend, backends[backend], m, system_msg,  # noqa: E731
                                user_msg, args.timeout, cwd)
    else:
        api_key = os.environ.get("OPENROUTER_API_KEY", "").strip()
        if not api_key:
            die("OPENROUTER_API_KEY is not set. Either get a key at "
                "https://openrouter.ai/keys, or use a CLI you are already signed "
                "in to: --backend codex | gemini | claude")
        run = lambda m: ask_openrouter(m, system_msg, user_msg, api_key,  # noqa: E731
                                       args.temperature, args.timeout)

    print(header, file=sys.stderr)

    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, len(models))) as pool:
        results = list(pool.map(run, models))

    # ---- report -----------------------------------------------------------
    chunks = [f"# 外部意见 / Outside opinion\n\n_{datetime.now(timezone.utc).astimezone():%Y-%m-%d %H:%M} · via {route}_\n"]
    failures = 0
    for r in results:
        if r.get("error"):
            failures += 1
            chunks.append(f"\n---\n\n## ❌ {r['model']}\n\n```\n{r['error']}\n```\n")
            continue
        usage = r.get("usage") or {}
        meta = f"{r['seconds']}s"
        if usage.get("total_tokens"):
            meta += f" · {usage['total_tokens']:,} tokens"
        chunks.append(f"\n---\n\n## 🔎 {r['model']}\n\n_{meta}_\n\n{r['text']}\n")

    out = "".join(chunks)
    print(out)

    if args.save:
        Path(args.save).expanduser().write_text(out, encoding="utf-8")
        print(f"\nsaved to {args.save}", file=sys.stderr)

    if failures == len(results):
        sys.exit(1)


if __name__ == "__main__":
    main()
